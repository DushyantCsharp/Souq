// Regenerates every artefact derived from the contracts in this package.
//
//   node scripts/codegen.ts                     # write into the repo
//   node scripts/codegen.ts --out-root <dir>    # write the same relative tree under <dir> (drift check)
//
// Inputs are always read from the repo; only output locations move with --out-root, so the drift
// check compares like with like.
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

import { type CodegenConfig, generate } from "@graphql-codegen/cli";
import openapiTS, { astToString } from "openapi-typescript";

export const CONTRACTS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REPO_ROOT = resolve(CONTRACTS_DIR, "../..");

// Pinned so the generated SDK is byte-identical across machines; bump deliberately and re-run codegen.
const OPENAPI_PYTHON_CLIENT = "openapi-python-client==0.29.1";

/** Every generated path, relative to the repo root. check-drift.ts diffs exactly these. */
export const OUTPUTS = {
  publicApi: "packages/contracts/generated/public-api.d.ts",
  searchInternal: "packages/contracts/generated/search-internal.d.ts",
  feedsInternal: "packages/contracts/generated/feeds-internal.d.ts",
  gatewayGraphql: "apps/gateway/src/generated/graphql.ts",
  gatewaySchema: "apps/gateway/src/generated/schema.ts",
  storefrontGql: "apps/storefront/src/gql",
  adminSdk: "libs/admin-sdk/src/souq_admin_sdk",
} as const;

const SCHEMA_GRAPHQL = join(CONTRACTS_DIR, "schema.graphql");
const PUBLIC_OPENAPI = join(CONTRACTS_DIR, "openapi.yaml");
const STOREFRONT_DOCUMENTS = join(REPO_ROOT, "apps/storefront/src/graphql/**/*.graphql");

/**
 * The real spec is exported from FastAPI by the owning service; until it exists the hand-written
 * provisional spec (kept in step with CLAUDE.md) stands in so the gateway can be built.
 */
export function internalSpec(service: "search-internal" | "feeds-internal"): string {
  const real = join(CONTRACTS_DIR, service, "openapi.json");
  return existsSync(real) ? real : join(CONTRACTS_DIR, service, "openapi.provisional.json");
}

function banner(source: string): string {
  const rel = source.startsWith(REPO_ROOT) ? source.slice(REPO_ROOT.length + 1) : source;
  return `// Generated by packages/contracts/scripts/codegen.ts from ${rel}. Do not edit.\n`;
}

async function writeOut(outRoot: string, rel: string, content: string): Promise<void> {
  const target = join(outRoot, rel);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, "utf8");
}

async function openapiTypes(outRoot: string, source: string, rel: string): Promise<void> {
  const ast = await openapiTS(pathToFileURL(source), {
    // Request fields with server-side defaults stay optional (the gateway may omit them).
    defaultNonNullable: false,
    alphabetize: false,
  });
  await writeOut(outRoot, rel, banner(source) + astToString(ast));
}

async function graphqlOutputs(outRoot: string): Promise<void> {
  const sdl = await readFile(SCHEMA_GRAPHQL, "utf8");
  // JSON.stringify rather than a template literal: descriptions contain backticks.
  await writeOut(
    outRoot,
    OUTPUTS.gatewaySchema,
    `${banner(SCHEMA_GRAPHQL)}export const typeDefs: string = ${JSON.stringify(sdl)};\n`,
  );

  const config: CodegenConfig = {
    schema: SCHEMA_GRAPHQL,
    documents: STOREFRONT_DOCUMENTS,
    ignoreNoDocuments: true,
    silent: true,
    generates: {
      [`${join(outRoot, OUTPUTS.storefrontGql)}/`]: {
        preset: "client",
        // Documents live in .graphql files and inline their fields, so unmasked types are what the UI wants.
        presetConfig: { fragmentMasking: false },
        config: { documentMode: "string", enumsAsTypes: true, useTypeImports: true },
      },
      [join(outRoot, OUTPUTS.gatewayGraphql)]: {
        plugins: [{ add: { content: banner(SCHEMA_GRAPHQL) } }, "typescript", "typescript-resolvers"],
        config: {
          useTypeImports: true,
          enumsAsTypes: true,
          contextType: "../graphql/context.js#GraphQLContext",
        },
      },
    },
  };
  // graphql-codegen resolves presets/plugins from process.cwd(); pin it so the script works from any dir.
  const cwd = process.cwd();
  process.chdir(CONTRACTS_DIR);
  try {
    await generate(config, true);
  } finally {
    process.chdir(cwd);
  }
}

function run(cmd: string, args: string[], cwd: string): void {
  execFileSync(cmd, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
}

async function adminSdk(outRoot: string): Promise<void> {
  const work = await mkdtemp(join(tmpdir(), "souq-admin-sdk-"));
  try {
    const pkgDir = join(work, "souq_admin_sdk");
    run(
      "uvx",
      [
        "--from",
        OPENAPI_PYTHON_CLIENT,
        "openapi-python-client",
        "generate",
        "--path",
        PUBLIC_OPENAPI,
        "--config",
        join(CONTRACTS_DIR, "admin-sdk.config.yaml"),
        // Overrides query-param serialisation so `filters` is sent deepObject-style, as the contract says.
        "--custom-template-path",
        join(CONTRACTS_DIR, "admin-sdk-templates"),
        "--meta",
        "none",
        "--output-path",
        pkgDir,
        "--overwrite",
      ],
      work,
    );
    // Format in the scratch dir with the workspace's locked ruff and the SDK's own config, so the result
    // does not depend on where --out-root points.
    const ruffConfig = join(REPO_ROOT, "libs/admin-sdk/pyproject.toml");
    run("uv", ["run", "--no-sync", "ruff", "check", "--fix-only", "--quiet", "--config", ruffConfig, pkgDir], REPO_ROOT);
    run("uv", ["run", "--no-sync", "ruff", "format", "--quiet", "--config", ruffConfig, pkgDir], REPO_ROOT);

    const target = join(outRoot, OUTPUTS.adminSdk);
    await rm(target, { recursive: true, force: true });
    await mkdir(dirname(target), { recursive: true });
    await cp(pkgDir, target, { recursive: true });
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

export async function codegen(outRoot: string = REPO_ROOT): Promise<void> {
  await openapiTypes(outRoot, PUBLIC_OPENAPI, OUTPUTS.publicApi);
  await openapiTypes(outRoot, internalSpec("search-internal"), OUTPUTS.searchInternal);
  await openapiTypes(outRoot, internalSpec("feeds-internal"), OUTPUTS.feedsInternal);
  // The client preset only replaces files it emits; clear the dir so deleted documents disappear.
  await rm(join(outRoot, OUTPUTS.storefrontGql), { recursive: true, force: true });
  await graphqlOutputs(outRoot);
  await adminSdk(outRoot);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const { values } = parseArgs({ options: { "out-root": { type: "string" } } });
  const outRoot = values["out-root"] ? resolve(values["out-root"]) : REPO_ROOT;
  await codegen(outRoot);
  console.warn(`codegen: wrote ${Object.keys(OUTPUTS).length} targets under ${outRoot}`);
}
